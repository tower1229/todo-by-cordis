import { test, expect } from "@playwright/test";
import { serve } from "@hono/node-server";
import { serveStatic } from "@hono/node-server/serve-static";
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { once } from "node:events";
import { Workspace } from "../../src/server/workspace.js";
import { EvolutionDomain } from "../../src/server/evolution-domain.js";
import { ExperienceSessionHost } from "../../src/server/experience-session.js";
import { Evolution } from "../../src/evolution/evolution.js";
import { createApp } from "../../src/server/app.js";
import { PlanningViewDriver } from "../app/planning-view-fixture.js";
import type { InvestigationState } from "../../src/shared/change-spec.js";
import { hash } from "../../src/release/storage.js";

test("原生来源视图冻结、原文补读与两阶段预算续行跨重启，体验后显式应用",async({page},info)=>{
  test.setTimeout(180000);
  const directory=info.outputPath("backend");await mkdir(directory,{recursive:true});
  const filename=join(directory,"workspace.db");
  let w=await Workspace.open(filename);
  let sessions=new ExperienceSessionHost(w);
  let driver=new PlanningViewDriver({invalidConclusion:true,badViewCandidate:true});
  let e=new Evolution(w.db,driver,new EvolutionDomain(w),sessions,{calls:5,candidates:1,milliseconds:600000});
  const appForHost=()=>{
    const app=createApp(w,e,sessions);
    app.use("/*",serveStatic({root:"./dist/web"}));app.get("*",serveStatic({path:"./dist/web/index.html"}));return app;
  };
  let app=appForHost();
  const server=serve({fetch:request=>app.fetch(request),hostname:"127.0.0.1",port:0});
  if(!server.listening)await once(server,"listening");
  const address=server.address();if(!address||typeof address==="string")throw new Error("address");
  const url=`http://127.0.0.1:${address.port}`;
  const snapshot=()=>e.observe();
  const status=async(value:string)=>expect.poll(async()=>(await snapshot()).run?.status,{timeout:60000}).toBe(value);
  const open=async()=>{await page.goto(url);await page.getByRole("button",{name:"改进应用",exact:true}).click();};
  const restart=async()=>{
    await e.close();await sessions.close();await w.close();
    w=await Workspace.open(filename);sessions=new ExperienceSessionHost(w);
    driver=new PlanningViewDriver({inspectAfterRaw:true,badViewCandidate:true});
    e=new Evolution(w.db,driver,new EvolutionDomain(w),sessions,{calls:99,candidates:99,milliseconds:9999999});
    app=appForHost();expect(driver.requests).toHaveLength(0);
  };
  try{
    await open();
    await page.getByRole("textbox",{name:"告诉 AI 你的需求"}).fill("完成前填写复盘，其他行为不变");
    await page.getByRole("button",{name:"发送需求"}).click();await status("ready");
    await page.getByRole("button",{name:"开始执行",exact:true}).click();await status("awaiting-apply");
    await page.getByRole("button",{name:"确认应用",exact:true}).click();await status("succeeded");
    const base=w.composition();
    await page.getByRole("button",{name:"继续修改",exact:true}).click();
    await page.getByRole("textbox",{name:"告诉 AI 你的需求"}).fill("复盘至少三个字，其他行为不变");
    await page.getByRole("button",{name:"发送需求"}).click();await status("awaiting-budget");
    const paused=(await snapshot()).run!;expect(paused.budget?.callsUsed).toBe(3);
    expect(paused.status).toBe("awaiting-budget");
    await restart();await page.setViewportSize({width:320,height:850});await open();
    expect((await snapshot()).run?.id).toBe(paused.id);
    await expect(page.getByRole("button",{name:"继续进行",exact:true})).toBeVisible();
    await page.screenshot({path:info.outputPath("planning-pause-320.png"),fullPage:true});
    await page.getByRole("button",{name:"继续进行",exact:true}).click();await status("awaiting-acceptance");
    await page.getByRole("button",{name:"确认业务验收修订",exact:true}).click();await status("ready");
    const ready=(await snapshot()).run!;if(ready.status!=="ready")throw new Error("ready");
    const frozen=hash(ready.plan);
    expect(ready.plan.binding?.materials.some(item=>item.source?.ref==="active-acceptance")).toBe(true);
    expect(ready.plan.binding?.materials.some(item=>item.ref==="active-acceptance")).toBe(true);
    await page.getByRole("button",{name:"开始执行",exact:true}).click();await status("awaiting-budget");
    const execution=(await snapshot()).run!;if(execution.status!=="awaiting-budget")throw new Error("pause");
    expect(execution.pause.resource).toBe("candidates");expect(execution.pause.resume).toBe("execute");
    await expect(page.getByRole("textbox",{name:"告诉 AI 你的需求"})).toHaveCount(0);
    expect(w.composition()).toEqual(base);
    await restart();await open();
    expect((await snapshot()).run?.id).toBe(paused.id);
    await page.getByRole("button",{name:"继续进行",exact:true}).click();await status("awaiting-apply");
    const checked=await snapshot();const run=checked.run!;
    expect(run.id).toBe(paused.id);expect(run.budget?.efficiencyTarget).toBe(5);
    expect(run.budget?.callsUsed).toBe(8);expect(run.budget?.grants).toHaveLength(2);
    if(!("plan" in run)||!run.plan)throw new Error("plan");expect(hash(run.plan)).toBe(frozen);
    expect(checked.candidates?.filter(item=>!item.passed)).toHaveLength(1);
    expect(checked.candidates?.filter(item=>item.passed)).toHaveLength(1);
    await page.setViewportSize({width:1360,height:950});
    await page.screenshot({path:info.outputPath("candidate-desktop.png"),fullPage:true});
    await page.getByRole("button",{name:"体验",exact:true}).click();
    await expect(page.getByRole("status",{name:"候选体验提示"})).toBeVisible();
    expect(w.composition()).toEqual(base);
    await page.getByRole("button",{name:"结束体验",exact:true}).click();
    await page.getByRole("button",{name:"改进应用",exact:true}).click();
    await page.getByRole("button",{name:"确认应用",exact:true}).click();await status("succeeded");
    expect(w.composition().versionId).not.toBe(base.versionId);
    const record=JSON.parse(String(w.db.prepare("SELECT body FROM evolution_runs WHERE id=?").get(run.id)!.body)) as {investigation:InvestigationState};
    const receipts=record.investigation.deliveries.flatMap(item=>item.materials);
    expect(receipts.some(item=>item.source?.ref==="active-acceptance")).toBe(true);
    expect(receipts.some(item=>item.ref==="active-acceptance")).toBe(true);
    const calls=w.db.prepare("SELECT body FROM evolution_calls WHERE runId=? ORDER BY id").all(run.id).map(item=>JSON.parse(String(item.body)));
    await writeFile(join(directory,"calls.json"),JSON.stringify(calls,null,2));
    expect(calls.filter(item=>item.phase==="admission")).toHaveLength(1);
    expect(calls.filter(item=>item.phase==="review")).toHaveLength(1);
  }finally{
    await writeFile(join(directory,"final-assistant.json"),JSON.stringify(await snapshot(),null,2));
    await e.close();await sessions.close();
    await new Promise<void>(resolve=>{server.close(()=>resolve());if("closeAllConnections" in server)server.closeAllConnections();});await w.close();
  }
});
